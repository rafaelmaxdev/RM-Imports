export function getTeamLogo(team: string, sport: "Futebol" | "NBA"): string | undefined {
  const category = sport === "NBA" ? "nba" : Object.hasOwn(COUNTRIES, team) ? "countries" : "soccer";
  const logos = category === "nba" ? NBA_TEAMS : category === "countries" ? COUNTRIES : CLUBS;
  if (!Object.hasOwn(logos, team)) return undefined;
  return `https://a.espncdn.com/i/teamlogos/${category}/500/${logos[team]}.png`;
}
